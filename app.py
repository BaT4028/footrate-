@app.route("/rate/<int:photo_id>", methods=["POST"])
@login_required
def rate(photo_id):
    try:
        score = int(request.form.get("score", ""))
    except (ValueError, TypeError):
        abort(400)

    if not 1 <= score <= 10:
        abort(400)

    with connect_db() as db:
        photo = db.execute(
            "SELECT * FROM public.photos WHERE id = %s",
            (photo_id,),
        ).fetchone()

        if not photo:
            abort(404)

        if photo["user_id"] == session["user_id"]:
            flash("A sajat kepedet nem ertekelheted.")
            return redirect(url_for("index"))

        db.execute(
            """
            INSERT INTO public.ratings (photo_id, user_id, score)
            VALUES (%s, %s, %s)
            ON CONFLICT (photo_id, user_id)
            DO UPDATE SET score = EXCLUDED.score
            """,
            (photo_id, session["user_id"], score),
        )

    flash("Ertekeles mentve vagy frissitve.")
    return redirect(url_for("index"))


# ---------------- DELETE PHOTO ----------------

@app.route("/delete/<int:photo_id>", methods=["POST"])
@login_required
def delete_photo(photo_id):
    with connect_db() as db:
        photo = db.execute(
            "SELECT * FROM public.photos WHERE id = %s",
            (photo_id,),
        ).fetchone()

        if not photo:
            abort(404)

        if photo["user_id"] != session["user_id"] and not is_admin():
            abort(403)

        try:
            storage_delete(photo["filename"])
        except Exception:
            app.logger.exception("Supabase torlesi hiba")
            flash("A kep torlese a tarhelyrol nem sikerult.")
            return redirect(url_for("index"))

        db.execute(
            "DELETE FROM public.photos WHERE id = %s",
            (photo_id,),
        )

    flash("Kep torolve.")
    return redirect(url_for("index"))


