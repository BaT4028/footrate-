# ---------------- UPLOAD ----------------

@app.route("/upload", methods=["POST"])
@login_required
def upload():
    file = request.files.get("photo")

    if not file or not file.filename:
        flash("Valassz ki egy kepet.")
        return redirect(url_for("index"))

    original = secure_filename(file.filename)

    if Path(original).suffix.lower() not in ALLOWED_EXTENSIONS:
        flash("Csak JPG, PNG vagy WEBP kep toltheto fel.")
        return redirect(url_for("index"))

    try:
        file.stream.seek(0)
        image = Image.open(file.stream)

        if image.format not in ALLOWED_FORMATS:
            raise ValueError("Nem tamogatott formatum.")

        image.verify()
        file.stream.seek(0)
        image = Image.open(file.stream)
        image.thumbnail((1600, 1600))

        output = io.BytesIO()
        image.convert("RGB").save(
            output, format="JPEG", quality=88, optimize=True
        )
        image_data = output.getvalue()

    except (UnidentifiedImageError, OSError, ValueError):
        flash("A fajl nem ervenyes kep.")
        return redirect(url_for("index"))

    filename = f"{secrets.token_hex(16)}.jpg"

    try:
        storage_upload(filename, image_data)
    except Exception:
        app.logger.exception("Supabase feltoltesi hiba")
        flash(
            "Nem sikerult feltolteni. Ellenorizd a Supabase bucketet "
            "es a Storage jogosultsagokat."
        )
        return redirect(url_for("index"))

    try:
        with connect_db() as db:
            db.execute(
                """
                INSERT INTO public.photos (user_id, filename)
                VALUES (%s, %s)
                """,
                (session["user_id"], filename),
            )

    except psycopg.Error:
        app.logger.exception("PostgreSQL adatmentesi hiba")

        try:
            storage_delete(filename)
        except Exception:
            app.logger.exception("A feltoltott kep takaritasa sikertelen")

        flash("A kep feltoltodott, de az adatainak mentese nem sikerult.")
        return redirect(url_for("index"))

    flash("A kep feltoltve.")
    return redirect(url_for("index"))


