@app.route("/upload", methods=["POST"])
@login_required
def upload():
    uploaded = request.files.get("photo")

    if not uploaded or not uploaded.filename:
        flash("Nem választottál képet.")
        return redirect(url_for("index"))

    try:
        raw = uploaded.read()

        if not raw:
            flash("A kiválasztott fájl üres.")
            return redirect(url_for("index"))

        if len(raw) > 5 * 1024 * 1024:
            flash("A kép legfeljebb 5 MB lehet.")
            return redirect(url_for("index"))

        try:
            image = Image.open(io.BytesIO(raw))
            image_format = image.format

            if image_format not in ALLOWED_FORMATS:
                flash("JPG, PNG vagy WEBP képet tölthetsz fel.")
                return redirect(url_for("index"))

            image.verify()

            image = Image.open(io.BytesIO(raw))
            image.thumbnail((1600, 1600))

            if image.mode != "RGB":
                image = image.convert("RGB")

            output = io.BytesIO()
            image.save(output, format="JPEG", quality=88, optimize=True)
            image_data = output.getvalue()

        except (UnidentifiedImageError, OSError, ValueError):
            flash("A fájl nem érvényes kép.")
            return redirect(url_for("index"))

        filename = f"{secrets.token_hex(16)}.jpg"
        storage_uploaded = False

        try:
            storage_upload(filename, image_data)
            storage_uploaded = True

            with connect_db() as conn:
                with conn.cursor() as cur:
                    cur.execute("""
                        INSERT INTO public.photos (user_id, filename)
                        VALUES (%s, %s)
                    """, (current_user_id(), filename))

            flash("A kép sikeresen feltöltve.")

        except Exception:
            logger.exception("Képfeltöltési hiba")

            if storage_uploaded:
                try:
                    storage_delete(filename)
                except Exception:
                    logger.exception("Feltöltött kép takarítási hibája")

            flash(
                "A képfeltöltés nem sikerült. "
                "Ellenőrizd a Render Logs naplót."
            )

    except Exception:
        logger.exception("Váratlan képfeltöltési hiba")
        flash("Hiba történt a kép feldolgozásakor.")

    return redirect(url_for("index"))


