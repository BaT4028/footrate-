@app.route("/")
@login_required
def index():
    user_id = current_user_id()

    with connect_db() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT
                    p.id,
                    p.user_id,
                    p.filename,
                    p.created_at,
                    u.username,

                    (
                        SELECT COUNT(*)
                        FROM public.photo_reactions r
                        WHERE r.photo_id = p.id
                          AND r.reaction_type = 'like'
                    ) AS like_count,

                    (
                        SELECT COUNT(*)
                        FROM public.photo_reactions r
                        WHERE r.photo_id = p.id
                          AND r.reaction_type = 'superheart'
                    ) AS superheart_count,

                    EXISTS (
                        SELECT 1
                        FROM public.photo_reactions r
                        WHERE r.photo_id = p.id
                          AND r.user_id = %s
                          AND r.reaction_type = 'like'
                    ) AS my_like,

                    EXISTS (
                        SELECT 1
                        FROM public.photo_reactions r
                        WHERE r.photo_id = p.id
                          AND r.user_id = %s
                          AND r.reaction_type = 'superheart'
                    ) AS my_superheart

                FROM public.photos p
                JOIN public.users u ON u.id = p.user_id
                ORDER BY p.created_at DESC, p.id DESC
            """, (user_id, user_id))

            photos = cur.fetchall()

    for photo in photos:
        photo["image_url"] = public_image_url(photo["filename"])

    return render_template(
        "index.html",
        photos=photos,
        username=session.get("username", "")
    )


