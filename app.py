@app.route("/delete/<int:photo_id>", methods=["POST"])
@login_required
def delete_photo(photo_id):
    photo = get_photo(photo_id)

    if not photo:
        abort(404)

    if photo["user_id"] != current_user_id():
        abort(403)

    try:
        with connect_db() as conn:
            with conn.cursor() as cur:
                cur.execute(
                    "DELETE FROM public.photos WHERE id = %s",
                    (photo_id,)
                )

        try:
            storage_delete(photo["filename"])
        except Exception:
            logger.exception("A kép adatbázisból törlődött, "
                             "de a Storage-törlés nem sikerült.")

        flash("A kép törölve.")

    except Exception:
        logger.exception("Képtörlési hiba")
        flash("A kép törlése nem sikerült.")

    return redirect(url_for("index"))


