@app.route("/react/<int:photo_id>/<reaction_type>", methods=["POST"])
@login_required
def react(photo_id, reaction_type):
    if reaction_type not in ("like", "superheart"):
        abort(404)

    photo = get_photo(photo_id)
    if not photo:
        abort(404)

    user_id = current_user_id()

    try:
        with connect_db() as conn:
            with conn.cursor() as cur:
                cur.execute("""
                    SELECT id
                    FROM public.photo_reactions
                    WHERE photo_id = %s
                      AND user_id = %s
                      AND reaction_type = %s
                """, (photo_id, user_id, reaction_type))

                existing = cur.fetchone()

                if existing:
                    cur.execute("""
                        DELETE FROM public.photo_reactions
                        WHERE id = %s
                    """, (existing["id"],))
                else:
                    cur.execute("""
                        INSERT INTO public.photo_reactions
                            (photo_id, user_id, reaction_type)
                        VALUES (%s, %s, %s)
                        ON CONFLICT (photo_id, user_id, reaction_type)
                        DO NOTHING
                    """, (photo_id, user_id, reaction_type))

    except Exception:
        logger.exception("Reakciómentési hiba")
        flash("A reakció mentése nem sikerült.")

    return redirect(url_for("index"))


