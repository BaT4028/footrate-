@app.route("/comments/<int:photo_id>")
@login_required
def comments(photo_id):
    if not get_photo(photo_id):
        return jsonify({"error": "A kép nem található."}), 404

    try:
        with connect_db() as conn:
            with conn.cursor() as cur:
                cur.execute("""
                    SELECT c.id, c.body, c.created_at, u.username
                    FROM public.comments c
                    JOIN public.users u ON u.id = c.user_id
                    WHERE c.photo_id = %s
                    ORDER BY c.created_at ASC, c.id ASC
                    LIMIT 200
                """, (photo_id,))
                rows = cur.fetchall()

        return jsonify({
            "comments": [
                {
                    "id": row["id"],
                    "body": row["body"],
                    "username": row["username"],
                    "created_at": row["created_at"].isoformat()
                }
                for row in rows
            ]
        })

    except Exception:
        logger.exception("Kommentek lekérési hibája")
        return jsonify({"error": "A kommentek betöltése nem sikerült."}), 500


