@app.route("/register", methods=["GET", "POST"])
def register():
    if current_user_id():
        return redirect(url_for("index"))

    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")

        if not 3 <= len(username) <= 30:
            flash("A felhasználónév 3–30 karakter legyen.")
            return render_template("register.html")

        if not username.replace("_", "").replace("-", "").isalnum():
            flash("A felhasználónév csak betűket, számokat, _ és - jelet tartalmazhat.")
            return render_template("register.html")

        if len(password) < 8:
            flash("A jelszó legalább 8 karakter legyen.")
            return render_template("register.html")

        try:
            with connect_db() as conn:
                with conn.cursor() as cur:
                    cur.execute("""
                        INSERT INTO public.users (username, password_hash)
                        VALUES (%s, %s)
                        RETURNING id
                    """, (
                        username,
                        generate_password_hash(password)
                    ))
                    new_user = cur.fetchone()

            session.clear()
            session["user_id"] = new_user["id"]
            session["username"] = username
            return redirect(url_for("index"))

        except psycopg.errors.UniqueViolation:
            flash("Ez a felhasználónév már foglalt.")
        except Exception:
            logger.exception("Regisztrációs hiba")
            flash("A regisztráció nem sikerült.")

    return render_template("register.html")


