def public_image_url(filename):
    safe_name = quote(filename, safe="/")
    return (
        f"{SUPABASE_URL}/storage/v1/object/public/"
        f"{BUCKET_NAME}/{safe_name}"
    )


def storage_upload(filename, data):
    return supabase.storage.from_(BUCKET_NAME).upload(
        path=filename,
        file=data,
        file_options={
            "content-type": "image/jpeg",
            "upsert": "false",
            "cache-control": "3600",
        }
    )


def storage_delete(filename):
    if filename:
        return supabase.storage.from_(BUCKET_NAME).remove([filename])


def current_user_id():
    return session.get("user_id")


def login_required(view):
    from functools import wraps

    @wraps(view)
    def wrapped(*args, **kwargs):
        if not current_user_id():
            return redirect(url_for("login"))
        return view(*args, **kwargs)

    return wrapped


def get_photo(photo_id):
    with connect_db() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT p.id, p.user_id, p.filename, u.username
                FROM public.photos p
                JOIN public.users u ON u.id = p.user_id
                WHERE p.id = %s
            """, (photo_id,))
            return cur.fetchone()


