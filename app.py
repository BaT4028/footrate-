# ---------------- CONFIG ----------------

BASE_DIR = Path(__file__).resolve().parent
load_dotenv(BASE_DIR / ".env")

SUPABASE_URL = os.getenv("SUPABASE_URL", "").strip()
SUPABASE_KEY = os.getenv("SUPABASE_KEY", "").strip()
DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
BUCKET_NAME = "FootPhotos"

if not SUPABASE_URL or not SUPABASE_KEY:
    raise RuntimeError("Hianyzik a SUPABASE_URL vagy SUPABASE_KEY a .env fajlbol.")

if not DATABASE_URL:
    raise RuntimeError("Hianyzik a DATABASE_URL a .env fajlbol.")

supabase = create_client(SUPABASE_URL, SUPABASE_KEY)

app = Flask(__name__)
app.config["SECRET_KEY"] = (
    os.getenv("FOOTRATE_SECRET_KEY") or secrets.token_hex(32)
)
app.config["MAX_CONTENT_LENGTH"] = 5 * 1024 * 1024
app.config["ADMIN_USERNAME"] = os.getenv(
    "FOOTRATE_ADMIN_USERNAME", "Axel"
).strip()

CSRFProtect(app)

ALLOWED_FORMATS = {"JPEG", "PNG", "WEBP"}
ALLOWED_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp"}


# ---------------- POSTGRESQL DATABASE ----------------

def connect_db():
    return psycopg.connect(
        DATABASE_URL,
        connect_timeout=10,
        row_factory=dict_row
    )


def init_db():
    with connect_db() as db:
        db.execute("""
            CREATE TABLE IF NOT EXISTS public.users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL
            )
        """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS public.photos (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES public.users(id) ON DELETE CASCADE,
                filename TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS public.ratings (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                photo_id BIGINT NOT NULL
                    REFERENCES public.photos(id) ON DELETE CASCADE,
                user_id BIGINT NOT NULL
                    REFERENCES public.users(id) ON DELETE CASCADE,
                score INTEGER NOT NULL CHECK(score BETWEEN 1 AND 10),
                UNIQUE(photo_id, user_id)
            )
        """)

        db.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique
            ON public.users (LOWER(username))
        """)


init_db()


# ---------------- HELPERS ----------------

def is_admin():
    configured = app.config["ADMIN_USERNAME"]
    current = session.get("username", "")
    return bool(
        configured and current
        and configured.casefold() == current.casefold()
    )


def login_required(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if "user_id" not in session:
            return redirect(url_for("login"))
        return fn(*args, **kwargs)
    return wrapper


def public_image_url(filename):
    return (
        f"{SUPABASE_URL.rstrip('/')}/storage/v1/object/public/"
        f"{quote(BUCKET_NAME)}/{quote(filename)}"
    )


def storage_upload(filename, data):
    return supabase.storage.from_(BUCKET_NAME).upload(
        path=filename,
        file=data,
        file_options={
            "content-type": "image/jpeg",
            "upsert": "false",
            "cache-control": "3600",
        },
    )


def storage_delete(filename):
    return supabase.storage.from_(BUCKET_NAME).remove([filename])


# ---------------- SECURITY HEADERS ----------------

@app.after_request
def security_headers(response):
    response.headers["X-Content-Type-Options"] = "nosniff"
    response.headers["X-Frame-Options"] = "DENY"
    response.headers["Referrer-Policy"] = "same-origin"
    response.headers["Content-Security-Policy"] = (
        "default-src 'self'; "
        "img-src 'self' data: https:; "
        "style-src 'self' 'unsafe-inline'; "
        "form-action 'self'; frame-ancestors 'none'; base-uri 'self'"
    )
    return response


# ---------------- HOME ----------------

@app.route("/")
@login_required
def index():
    with connect_db() as db:
        rows = db.execute("""
            SELECT
                p.id,
                p.filename,
                p.user_id,
                p.created_at,
                u.username,
                ROUND(AVG(r.score), 1) AS average,
                COUNT(r.id) AS rating_count,
                mine.score AS my_score
            FROM public.photos p
            JOIN public.users u ON u.id = p.user_id
            LEFT JOIN public.ratings r ON r.photo_id = p.id
            LEFT JOIN public.ratings mine
                ON mine.photo_id = p.id
                AND mine.user_id = %s
            GROUP BY p.id, u.username, mine.score
            ORDER BY p.created_at DESC
        """, (session["user_id"],)).fetchall()

    photos = []
    for row in rows:
        photo = dict(row)
        photo["image_url"] = public_image_url(photo["filename"])
        photos.append(photo)

    return render_template(
        "index.html",
        photos=photos,
        username=session["username"],
        admin=is_admin(),
    )


# ---------------- REGISTER ----------------

@app.route("/register", methods=["GET", "POST"])
def register():
    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")

        if (
            not 3 <= len(username) <= 20
            or not all(c.isalnum() or c in "_-" for c in username)
        ):
            flash("A felhasznalonev 3-20 karakter legyen.")
            return render_template("register.html")

        if len(password) < 8:
            flash("A jelszo legalabb 8 karakter legyen.")
            return render_template("register.html")

        try:
            with connect_db() as db:
                user = db.execute(
                    """
                    INSERT INTO public.users (username, password_hash)
                    VALUES (%s, %s)
                    RETURNING id
                    """,
                    (username, generate_password_hash(password)),
                ).fetchone()

                user_id = user["id"]

        except psycopg.IntegrityError:
            flash("Ez a felhasznalonev mar foglalt.")
            return render_template("register.html")

        session.clear()
        session["user_id"] = user_id
        session["username"] = username
        return redirect(url_for("index"))

    return render_template("register.html")


# ---------------- LOGIN ----------------

@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")

        with connect_db() as db:
            user = db.execute(
                """
                SELECT *
                FROM public.users
                WHERE LOWER(username) = LOWER(%s)
                """,
                (username,),
            ).fetchone()

        if not user or not check_password_hash(
            user["password_hash"], password
        ):
            flash("Hibas felhasznalonev vagy jelszo.")
            return render_template("login.html")

        session.clear()
        session["user_id"] = user["id"]
        session["username"] = user["username"]
        return redirect(url_for("index"))

    return render_template("login.html")


